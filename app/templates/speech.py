from typing import Optional

def format_kobo_to_speech(kobo: int) -> str:
    """
    Deterministically formats an integer kobo amount into spoken Nigerian English text.
    Examples:
        500000 -> "5,000 Naira"
        150000 -> "1,500 Naira"
        50050 -> "500 Naira and 50 kobo"
        50 -> "50 kobo"
        0 -> "0 Naira"
    """
    naira = kobo // 100
    rem_kobo = kobo % 100
    
    if naira > 0 and rem_kobo > 0:
        return f"{naira:,} Naira and {rem_kobo} kobo"
    elif naira > 0:
        return f"{naira:,} Naira"
    else:
        return f"{rem_kobo} kobo"

def build_transfer_confirmation_prompt(amount_kobo: int, recipient: str) -> str:
    """Deterministic confirmation prompt. Never generated by an LLM."""
    formatted_amount = format_kobo_to_speech(amount_kobo)
    return f"Transfer {formatted_amount} to {recipient}. Say 'confirm' to proceed, or 'cancel' to abort."

def build_clarification_prompt(reason: str, recipient: Optional[str] = None) -> str:
    """Deterministic clarification prompts for ambiguous or missing parameters."""
    if reason == "missing_recipient":
        return "Who would you like to send money to?"
    elif reason == "missing_amount":
        if recipient:
            return f"How much would you like to send to {recipient}?"
        return "How much would you like to send?"
    elif reason == "missing_amount_and_recipient":
        return "Who would you like to send money to, and how much?"
    elif reason == "amount_mismatch" or reason == "unparseable_amount":
        return "I could not verify the exact amount. Please repeat the amount clearly."
    elif reason == "low_confidence":
        return "I didn't quite catch that. Could you please repeat what you would like to do?"
    elif reason == "multiple_tools":
        return "I heard multiple requests. Please make one request at a time."
    elif reason == "unknown_tool":
        return "That action is not available. You can check your balance or make a transfer."
    else:
        return "Could you please clarify your request?"

def build_confirmed_prompt(amount_kobo: int, recipient: str) -> str:
    """Deterministic prompt upon successful token minting."""
    formatted_amount = format_kobo_to_speech(amount_kobo)
    return f"Transfer of {formatted_amount} to {recipient} confirmed."

def build_cancelled_prompt() -> str:
    """Deterministic prompt upon user cancellation."""
    return "Transaction cancelled."
