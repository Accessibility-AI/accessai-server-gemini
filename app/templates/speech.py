def format_kobo_to_speech(kobo: int, lang: str = "en") -> str:
    """Deterministically formats an integer kobo amount into spoken text.

    Supports en, pcm, yo, ig, ha, fr, de, es.
    """
    naira = kobo // 100
    rem_kobo = kobo % 100

    if lang in ["fr", "es"]:
        currency_name = "Nairas"
    else:
        currency_name = "Naira"

    if naira > 0 and rem_kobo > 0:
        return f"{naira:,} {currency_name} and {rem_kobo} kobo"
    elif naira > 0:
        return f"{naira:,} {currency_name}"
    else:
        return f"{rem_kobo} kobo"


